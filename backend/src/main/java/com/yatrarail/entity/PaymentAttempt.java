package com.yatrarail.entity;

import jakarta.persistence.*;
import lombok.*;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * Phase 5 — an append-only record of one <i>attempt</i> to pay for a booking.
 * <p>
 * <b>Why this exists.</b> {@link Payment} is deliberately one row per booking: it is the settled,
 * authoritative answer to "was this booking paid for, and how much". Before Phase 5 that made it the
 * only place a payment was recorded, which loses information that an operator and a passenger both
 * need:
 * <ul>
 *   <li>a failed attempt followed by a successful one left only the success — the passenger's
 *       "I already tried and it didn't work" had no record anywhere;</li>
 *   <li>a <i>re</i>-payment after a failure overwrote the first attempt's transaction reference, so
 *       the original reference could not be quoted to a support agent afterwards;</li>
 *   <li>there was no timestamped ledger to reconcile money against, only a mutable current state.</li>
 * </ul>
 * This table is that ledger. Rows are only ever inserted: a new attempt writes a new row and never
 * touches an earlier one, and {@link Payment} remains the current settled state. The attempt's
 * {@code idempotencyKey} is intentionally <i>not</i> unique here — two different attempts may
 * legitimately arrive under different keys, and only {@link Payment}'s key is a replay guard.
 * <p>
 * The amount is copied from the booking at attempt time rather than referenced, so a later
 * re-pricing of the booking cannot retroactively change what an attempt was worth.
 */
@Entity
@Table(name = "payment_attempts", indexes = {
        @Index(name = "idx_attempt_booking", columnList = "booking_id, created_at"),
        @Index(name = "idx_attempt_user", columnList = "user_id, created_at"),
        @Index(name = "idx_attempt_status", columnList = "status"),
        @Index(name = "idx_attempt_reference", columnList = "transaction_reference", unique = true)
})
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class PaymentAttempt {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "booking_id", nullable = false)
    private Booking booking;

    /**
     * The account that attempted the payment. Denormalised from the booking so a payment history can
     * be read without joining through the booking, and so a later ownership change cannot rewrite
     * who actually paid.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /** UPI / CARD / NETBANKING. Mock/simulated, as with {@link Payment}. */
    @Column(nullable = false, length = 20)
    private String method;

    /** The amount this attempt tried to settle, snapshotted from the booking. */
    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal amount;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private PaymentStatus status;

    /** Unique per attempt, and distinct from {@link Payment}'s reference for the settled attempt. */
    @Column(name = "transaction_reference", nullable = false, length = 40)
    private String transactionReference;

    /** The {@code Idempotency-Key} the client sent, if any. Kept for tracing, not for de-duplication. */
    @Column(name = "idempotency_key", length = 80)
    private String idempotencyKey;

    /**
     * False when this attempt was generated by a server-side job rather than by the passenger, e.g.
     * a re-charge. Nothing generates one today; the column exists so a reader can always tell a
     * client-driven attempt from an automatic one.
     */
    @Builder.Default
    @Column(name = "client_initiated", nullable = false)
    private Boolean clientInitiated = true;

    @Column(nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @PrePersist
    protected void onCreate() {
        createdAt = LocalDateTime.now();
    }
}
